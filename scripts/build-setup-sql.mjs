#!/usr/bin/env node
/**
 * Builds the copy-paste SQL files in supabase/setup/ from supabase/migrations/.
 *
 *   node scripts/build-setup-sql.mjs
 *
 * printflow_full_setup.sql  — a NEW, empty Supabase project: every migration in
 *   one transaction. `alter type … add value` can't be used in the same
 *   transaction as the value, so those values are folded into the original
 *   `create type` statements instead (same end result).
 * update_<from>_partN.sql   — an EXISTING project that already ran the setup
 *   file up to <from>: the newer migrations, split so enum additions commit
 *   before anything uses them.
 * Every file records the migrations it applied, so `supabase db push` stays in sync.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const dir = join(root, "supabase/migrations");
const out = join(root, "supabase/setup");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const read = (f) => readFileSync(join(dir, f), "utf8");
const version = (f) => f.split("_")[0];
const name = (f) => f.replace(/^\d+_/, "").replace(/\.sql$/, "");
const ADD_VALUE = /alter type\s+([\w.]+)\s+add value\s+if not exists\s+'([^']+)'\s*;/gi;

const record = (list) =>
  [
    "create schema if not exists supabase_migrations;",
    "create table if not exists supabase_migrations.schema_migrations (version text primary key, statements text[], name text);",
    ...list.map((f) => `insert into supabase_migrations.schema_migrations (version, name) values ('${version(f)}', '${name(f)}') on conflict (version) do nothing;`),
  ].join("\n");
const section = (f, sql) => `\n-- ============================================================\n-- ${f}\n-- ============================================================\n${sql}\n`;

// ---- Full setup for a new project ----
const enumAdds = [];
for (const f of files) for (const m of read(f).matchAll(ADD_VALUE)) enumAdds.push({ type: m[1], value: m[2] });
let body = "";
for (const f of files) {
  let sql = read(f).replace(ADD_VALUE, (_all, type, value) => `-- (${type} '${value}' is included in the original create type)`);
  for (const { type, value } of enumAdds) {
    sql = sql.replace(new RegExp(`(create type\\s+${type.replace(".", "\\.")}\\s+as\\s+enum\\s*\\()([^)]*)\\)`, "i"), (_m, head, values) =>
      values.includes(`'${value}'`) ? `${head}${values})` : `${head}${values}, '${value}')`,
    );
  }
  body += section(f, sql);
}
writeFileSync(
  join(out, "printflow_full_setup.sql"),
  `-- PrintFlow: complete database setup for a NEW, EMPTY Supabase project.
-- Paste this whole file into Supabase → SQL Editor → New query, then click Run. Run it ONCE.
-- Generated by scripts/build-setup-sql.mjs from supabase/migrations (${files.length} migrations), in one
-- transaction: if anything fails, nothing is changed. It records the migrations so
-- 'npx supabase db push' later knows they are already applied.

begin;
${body}
-- Record the applied migrations for the Supabase CLI.
${record(files)}

commit;

select 'PrintFlow database ready' as result, (select count(*) from public.printers) as printers;
`,
);

// ---- Updates for existing projects, one per baseline (the last migration they ran) ----
const BASELINES = ["20261119000004", "20261120000003"];
const hasEnumAdd = (f) => {
  ADD_VALUE.lastIndex = 0;
  const found = ADD_VALUE.test(read(f));
  ADD_VALUE.lastIndex = 0;
  return found;
};
for (const FROM of BASELINES) {
  const newer = files.filter((f) => version(f) > FROM);
  const enumFiles = newer.filter(hasEnumAdd);
  const rest = newer.filter((f) => !enumFiles.includes(f));
  const parts = enumFiles.length ? 2 : 1;
  const header = (part, what) => `-- PrintFlow update${parts > 1 ? ` ${part} of ${parts}` : ""} — for a project whose last migration is ${FROM}.
-- ${what}
-- Paste into Supabase → SQL Editor → New query → Run.${parts > 1 ? " Run part 1 first, then part 2 as a NEW query." : ""}
-- Safe to re-run: nothing is applied twice. Generated by scripts/build-setup-sql.mjs.
`;
  const restSql = (part) => `${header(part, rest.map(name).join(", "))}
begin;
${rest.map((f) => section(f, read(f))).join("")}
${record(rest)}

commit;

select 'PrintFlow update complete' as result;
`;
  if (parts === 2) {
    writeFileSync(
      join(out, `update_${FROM}_part1.sql`),
      `${header(1, "Adds new enum values (must be committed before part 2 uses them).")}
${enumFiles.map((f) => section(f, read(f))).join("")}
${record(enumFiles)}

select 'Part 1 done — now run part 2' as result;
`,
    );
    writeFileSync(join(out, `update_${FROM}_part2.sql`), restSql(2));
  } else {
    writeFileSync(join(out, `update_${FROM}.sql`), restSql(1));
  }
  console.log(`update from ${FROM}: ${parts === 2 ? `part1 [${enumFiles.join(", ")}], part2 ` : ""}[${rest.join(", ")}]`);
}
console.log(`full setup: ${files.length} migrations`);
